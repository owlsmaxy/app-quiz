(() => {
  const aiConfigStorageKey = 'atlas-learn-ai-config-v1';
  const rateLimitWindowMs = 60000;
  const rateLimitMax = 12;
  const aiRequestTimestamps = [];
  let aiEndpoint = '';
  let aiApiKey = '';
  let aiEnabled = false;

  const explanationLevels = {
    beginner: 'Beginner',
    intermediate: 'Intermediate',
    advanced: 'Advanced'
  };

  function loadConfig() {
    try {
      const raw = localStorage.getItem(aiConfigStorageKey);
      if (!raw) return;
      const saved = JSON.parse(raw);
      aiEndpoint = typeof saved.aiEndpoint === 'string' ? saved.aiEndpoint.slice(0, 500) : '';
      aiApiKey = typeof saved.aiApiKey === 'string' ? saved.aiApiKey.slice(0, 200) : '';
      aiEnabled = Boolean(saved.aiEnabled);
    } catch (error) {
      console.error('Unable to read AI config.', error);
    }
  }
  function saveConfig() {
    try {
      localStorage.setItem(aiConfigStorageKey, JSON.stringify({ aiEndpoint, aiApiKey, aiEnabled }));
      return true;
    } catch (error) {
      console.error('Unable to save AI config.', error);
      return false;
    }
  }
  loadConfig();

  function configure(endpoint, apiKey, enabled) {
    aiEndpoint = typeof endpoint === 'string' ? endpoint : '';
    aiApiKey = typeof apiKey === 'string' ? apiKey : '';
    aiEnabled = Boolean(enabled);
    return saveConfig();
  }
  function getConfig() { return { aiEndpoint, aiApiKey, aiEnabled }; }

  function canMakeRequest() {
    const now = Date.now();
    while (aiRequestTimestamps.length && now - aiRequestTimestamps[0] > rateLimitWindowMs) {
      aiRequestTimestamps.shift();
    }
    return aiRequestTimestamps.length < rateLimitMax;
  }
  function recordRequest() {
    aiRequestTimestamps.push(Date.now());
  }
  function timeUntilNextRequest() {
    if (aiRequestTimestamps.length < rateLimitMax) return 0;
    const oldest = aiRequestTimestamps[0];
    return Math.max(0, rateLimitWindowMs - (Date.now() - oldest));
  }

  function escapeHtml(value) {
    return String(value ?? '').replace(/[&<>"']/g, char => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
  }

  function demoGenerateTopicOutline(query, level) {
    const term = query.trim();
    const levelLabel = explanationLevels[level] || 'Intermediate';
    const field = inferField(term);
    const subtopics = generateSubtopics(term, field, level);
    const prerequisites = generatePrerequisites(term, field, level);
    const pathway = generatePathway(term, field, level);
    const intro = generateIntroduction(term, field, levelLabel);
    const practiceQuestions = generatePracticeQuestions(term, field, level);
    return {
      aiGenerated: true,
      verified: false,
      query: term,
      level,
      levelLabel,
      field,
      introduction: intro,
      subtopics,
      prerequisites,
      pathway,
      practiceQuestions,
      note: 'This topic is not yet in the verified Atlas Learn catalogue. The outline below was generated by AI to help you start exploring. It is not academically verified and should be used alongside trusted textbooks, teachers or course materials.'
    };
  }

  function inferField(query) {
    const q = query.toLocaleLowerCase();
    const fields = [
      { keywords: ['python', 'javascript', 'java', 'c++', 'code', 'programming', 'software', 'algorithm', 'html', 'css', 'react', 'node', 'database', 'sql', 'api', 'git', 'debug'], field: 'Computer Science and Software Engineering' },
      { keywords: ['machine learning', 'ai ', 'artificial intelligence', 'neural', 'deep learning', 'llm', 'model', 'training data', 'supervised'], field: 'Artificial Intelligence and Machine Learning' },
      { keywords: ['math', 'mathematics', 'algebra', 'calculus', 'statistics', 'equation', 'geometry', 'probability', 'matrix'], field: 'Mathematics and Statistics' },
      { keywords: ['physics', 'quantum', 'force', 'energy', 'newton', 'electricity', 'magnetism', 'thermodynamics', 'relativity'], field: 'Physics' },
      { keywords: ['chemistry', 'molecule', 'atom', 'reaction', 'acid', 'base', 'mole', 'organic', 'periodic'], field: 'Chemistry' },
      { keywords: ['biology', 'cell', 'dna', 'gene', 'ecosystem', 'photosynthesis', 'organism', 'evolution', 'anatomy'], field: 'Biology and Life Sciences' },
      { keywords: ['medicine', 'health', 'anatomy', 'physiology', 'disease', 'patient', 'clinical', 'nursing', 'pharmacology'], field: 'Medicine and Health Sciences' },
      { keywords: ['history', 'war', 'empire', 'revolution', 'civilization', 'colonial', 'independence', 'heritage'], field: 'History and Political Science' },
      { keywords: ['geography', 'climate', 'map', 'population', 'migration', 'urban', 'landscape', 'weather'], field: 'Geography and Environmental Science' },
      { keywords: ['business', 'economics', 'finance', 'marketing', 'entrepreneur', 'accounting', 'management', 'trade'], field: 'Business, Economics and Finance' },
      { keywords: ['law', 'legal', 'court', 'constitution', 'rights', 'contract', 'justice', 'legislation'], field: 'Law and Political Science' },
      { keywords: ['english', 'language', 'linguistics', 'grammar', 'literature', 'poetry', 'novel', 'writing'], field: 'Languages and Linguistics' },
      { keywords: ['psychology', 'mind', 'behaviour', 'behavior', 'cognitive', 'mental', 'therapy', 'development'], field: 'Psychology and Sociology' },
      { keywords: ['agriculture', 'farming', 'crop', 'soil', 'livestock', 'nutrition', 'food'], field: 'Agriculture and Environmental Science' },
      { keywords: ['education', 'teaching', 'pedagogy', 'curriculum', 'classroom', 'assessment'], field: 'Education and Research' },
      { keywords: ['philosophy', 'ethics', 'logic', 'metaphysics', 'morality', 'truth', 'knowledge'], field: 'Philosophy' },
      { keywords: ['music', 'art', 'design', 'drawing', 'painting', 'dance', 'theatre', 'creative'], field: 'Arts, Music and Design' },
      { keywords: ['engineering', 'circuit', 'mechanical', 'civil', 'electrical', 'structure', 'materials'], field: 'Engineering and Technology' }
    ];
    for (const { keywords, field } of fields) {
      if (keywords.some(keyword => q.includes(keyword))) return field;
    }
    return 'General Studies';
  }

  function generateSubtopics(query, field, level) {
    const base = [
      { name: `Foundations of ${query}`, description: `Core ideas, definitions and history of ${query} at the ${levelLabel(level)} level.` },
      { name: `Key concepts in ${query}`, description: `Important terms, theories and principles learners should know.` },
      { name: `How ${query} is used in practice`, description: `Real-world examples and applications across contexts.` },
      { name: `Common challenges and misconceptions`, description: `Frequently misunderstood ideas and how to work through them.` },
      { name: `Next steps and related topics`, description: `What to study after mastering the basics of ${query}.` }
    ];
    if (level === 'advanced') {
      base.push({ name: `Current research in ${query}`, description: `Recent developments, open questions and academic debates.` });
      base.push({ name: `Advanced methods in ${query}`, description: `Specialised techniques and tools used by researchers.` });
    }
    return base;
  }

  function generatePrerequisites(query, field, level) {
    const common = ['Basic reading and comprehension', 'Curiosity and a willingness to practise'];
    if (level === 'intermediate') common.push('Foundational knowledge in a related school subject');
    if (level === 'advanced') common.push('Prior coursework in the discipline', 'Academic reading and writing skills');
    if (field.includes('Mathematics') || field.includes('Statistics')) common.push('Comfort with arithmetic and algebraic notation');
    if (field.includes('Computer') || field.includes('Artificial')) common.push('Basic computer use and file management');
    if (field.includes('Medicine') || field.includes('Health')) common.push('High-school level biology');
    if (field.includes('Law')) common.push('Strong reading comprehension and logical reasoning');
    return common.slice(0, 4);
  }

  function generatePathway(query, field, level) {
    const steps = [
      { step: 1, action: `Start with an introduction to ${query}`, detail: 'Learn the core definition, history and why the subject matters.' },
      { step: 2, action: 'Study key concepts and terminology', detail: 'Work through definitions, formulas or frameworks used in the field.' },
      { step: 3, action: 'Practise with examples and exercises', detail: 'Apply ideas to worked examples, then try questions on your own.' },
      { step: 4, action: 'Explore related topics', detail: 'Connect this subject to neighbouring disciplines and real-world uses.' },
      { step: 5, action: 'Go deeper or apply it', detail: 'Take a course, build a project or discuss with a teacher or mentor.' }
    ];
    if (level === 'advanced') {
      steps.push({ step: 6, action: 'Engage with current literature', detail: 'Read research papers, attend seminars and contribute to discussions.' });
    }
    return steps;
  }

  function generateIntroduction(query, field, levelLabel) {
    return `${query} is part of ${field}. At the ${levelLabel} level, you will explore its core ideas, learn its language and see how it applies to real situations. Begin with the foundations, practise regularly and connect new ideas to what you already know.`;
  }

  function generatePracticeQuestions(query, field, level) {
    const q = query.toLocaleLowerCase();
    const questions = [];
    if (field.includes('Mathematics') || field.includes('Statistics')) {
      questions.push({ prompt: `Explain in your own words what ${query} means and give one example.`, type: 'short-answer', answer: 'Open-ended response', explanation: 'There is no single correct answer; focus on a clear, accurate explanation.' });
    } else if (field.includes('Computer') || field.includes('Artificial')) {
      questions.push({ prompt: `Describe one way ${query} is used in everyday software or systems.`, type: 'short-answer', answer: 'Open-ended response', explanation: 'Look for a concrete, real-world application.' });
    } else {
      questions.push({ prompt: `What is the most important idea in ${query}, and why does it matter?`, type: 'short-answer', answer: 'Open-ended response', explanation: 'Identify a central concept and give a reason for its importance.' });
    }
    return questions;
  }

  function levelLabel(level) {
    return explanationLevels[level] || 'Intermediate';
  }

  async function explainQuestion(question, context, level = 'intermediate') {
    const payload = { action: 'explain-question', question, context, level };
    return callAI('explain-question', payload, () => demoExplainQuestion(question, context, level));
  }
  async function getHint(question, context, level = 'intermediate') {
    const payload = { action: 'get-hint', question, context, level };
    return callAI('get-hint', payload, () => demoGetHint(question, context, level));
  }
  async function explainAnswer(question, userAnswer, correctAnswer, level = 'intermediate') {
    const payload = { action: 'explain-answer', question, userAnswer, correctAnswer, level };
    return callAI('explain-answer', payload, () => demoExplainAnswer(question, userAnswer, correctAnswer, level));
  }
  async function guidedProblemSolving(problem, subject, level = 'intermediate') {
    const payload = { action: 'guided-problem-solving', problem, subject, level };
    return callAI('guided-problem-solving', payload, () => demoGuidedProblemSolving(problem, subject, level));
  }
  async function followUp(conversationHistory, newQuestion, level = 'intermediate') {
    const payload = { action: 'follow-up', conversationHistory, newQuestion, level };
    return callAI('follow-up', payload, () => demoFollowUp(conversationHistory, newQuestion, level));
  }
  async function discoverTopic(query, level = 'intermediate') {
    const payload = { action: 'discover-topic', query, level };
    return callAI('discover-topic', payload, () => demoGenerateTopicOutline(query, level));
  }

  async function callAI(action, payload, demoFallback) {
    const result = { aiGenerated: true, verified: false, error: null, data: null, usedDemo: false };
    if (!aiEnabled || !aiEndpoint) {
      result.usedDemo = true;
      try { result.data = await demoFallback(); } catch (error) { result.error = 'AI assistant is unavailable and demo mode failed.'; }
      return result;
    }
    if (!canMakeRequest()) {
      const waitMs = timeUntilNextRequest();
      result.error = `Rate limit reached. Try again in ${Math.ceil(waitMs / 1000)} seconds.`;
      result.usedDemo = true;
      try { result.data = await demoFallback(); } catch (error) { result.error = result.error || 'AI assistant is temporarily unavailable.'; }
      return result;
    }
    recordRequest();
    try {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), 30000);
      const response = await fetch(aiEndpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', ...(aiApiKey ? { Authorization: `Bearer ${aiApiKey}` } : {}) },
        body: JSON.stringify(payload),
        signal: controller.signal
      });
      clearTimeout(timeout);
      if (!response.ok) throw new Error(`AI service responded with status ${response.status}`);
      const data = await response.json();
      result.data = data;
      return result;
    } catch (error) {
      result.usedDemo = true;
      try { result.data = await demoFallback(); } catch (demoError) { result.error = 'AI service is unavailable. Please check your connection or configure a backend endpoint.'; }
      return result;
    }
  }

  function demoExplainQuestion(question, context, level) {
    const label = levelLabel(level);
    const breakDown = [
      'Read the question slowly and identify what it is asking you to find or show.',
      'Look for key words such as "calculate", "explain", "compare" or "describe".',
      'Identify the information given and the information missing.'
    ];
    if (level === 'beginner') breakDown.push('Try saying the question in your own words before answering.');
    if (level === 'advanced') breakDown.push('Consider any assumptions or constraints hidden in the wording.');
    return {
      type: 'explain-question',
      level,
      levelLabel: label,
      interpretation: `This question is asking about: ${escapeHtml(question)}`,
      whatItAsks: 'It wants you to work through the situation described and give a clear, supported answer.',
      keyConcepts: ['Read carefully', 'Identify given information', 'Apply the relevant idea'],
      steps: breakDown,
      terminology: 'Key terms are highlighted so you can look them up in your notes or textbook.',
      disclaimer: 'This is an AI-generated explanation. It is not academically verified.'
    };
  }

  function demoGetHint(question, context, level) {
    const label = levelLabel(level);
    const hints = [
      'Start by writing down what you already know from the question.',
      'Ask yourself: what is the first step I can take?',
      'Look for a formula, definition or example that matches this situation.'
    ];
    if (level === 'beginner') hints.push('Try drawing a sketch or listing the numbers involved.');
    if (level === 'advanced') hints.push('Consider whether a standard theorem or method applies directly.');
    return {
      type: 'get-hint',
      level,
      levelLabel: label,
      hint: hints[0],
      nextSteps: hints.slice(1),
      encouragement: 'Take your time. A small first step often reveals the rest of the path.',
      disclaimer: 'This is an AI-generated hint. It is not academically verified.'
    };
  }

  function demoExplainAnswer(question, userAnswer, correctAnswer, level) {
    const label = levelLabel(level);
    return {
      type: 'explain-answer',
      level,
      levelLabel: label,
      userAnswer: escapeHtml(String(userAnswer ?? '')),
      correctAnswer: escapeHtml(String(correctAnswer ?? '')),
      whyIncorrect: 'Your answer does not match the expected result. Check each step against the question requirements.',
      correctReasoning: `The correct answer is ${escapeHtml(String(correctAnswer ?? ''))}. This follows from applying the relevant concept to the information given in the question.`,
      example: 'For example, if the question asks for a calculation, redo the calculation slowly and compare each line with the correct working.',
      suggestion: 'Try a similar question to confirm you understand before moving on.',
      disclaimer: 'This is an AI-generated explanation. It is not academically verified.'
    };
  }

  function demoGuidedProblemSolving(problem, subject, level) {
    const label = levelLabel(level);
    const steps = [
      `Step 1: Restate the ${subject} problem in your own words and identify what is being asked.`,
      `Step 2: List the given information and any formulas or rules from ${subject} that apply.`,
      `Step 3: Carry out the first calculation or reasoning step and write down the result.`,
      `Step 4: Continue step by step, checking each result before moving to the next.`,
      `Step 5: State the final answer clearly and review whether it answers the original question.`
    ];
    if (level === 'beginner') steps.push('Tip: If you get stuck, go back to the definitions of the key terms.');
    if (level === 'advanced') steps.push('Tip: Consider edge cases and whether your answer makes sense at the limits.');
    return {
      type: 'guided-problem-solving',
      subject,
      level,
      levelLabel: label,
      problem: escapeHtml(String(problem ?? '')),
      steps,
      approach: 'Work through one step at a time. Do not rush to the final answer.',
      disclaimer: 'This is an AI-generated guide. It is not academically verified.'
    };
  }

  function demoFollowUp(history, newQuestion, level) {
    const label = levelLabel(level);
    const contextSummary = history && history.length
      ? `Earlier in this conversation we discussed: ${history.slice(-3).map(item => item.question || item.text || '').join(' ; ')}`
      : 'This is the start of our conversation.';
    return {
      type: 'follow-up',
      level,
      levelLabel: label,
      context: contextSummary,
      response: `That is a good follow-up question: "${escapeHtml(String(newQuestion ?? ''))}". Building on what we discussed, here is what to consider next...`,
      suggestion: 'If anything is still unclear, ask me to explain it another way or give another example.',
      disclaimer: 'This is an AI-generated response. It is not academically verified.'
    };
  }

  window.AtlasAI = Object.freeze({
    getConfig, configure, canMakeRequest, timeUntilNextRequest,
    explanationLevels, levelLabel,
    explainQuestion, getHint, explainAnswer, guidedProblemSolving, followUp, discoverTopic,
    demoGenerateTopicOutline
  });
})();
